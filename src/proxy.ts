import type { NextRequest } from 'next/server';
import { NextResponse } from 'next/server';
import createMiddleware from 'next-intl/middleware';
import { routing } from '@/i18n/routing';
import { auth } from '@/lib/auth';
import { isPathMatched } from '@/utils/path-helper';
import { sanitizeUrl } from '@/utils/url-helper';
import { AUTH_PATHS, PUBLIC_PATHS } from './constants/common';

const intlMiddleware = createMiddleware(routing);

function hasActiveSession(
  sessionData: Awaited<ReturnType<typeof auth.api.getSession>> | null
): boolean {
  if (!sessionData?.user?.id || !sessionData?.session?.id) return false;

  const expiresAt = sessionData.session.expiresAt;

  const expiresAtTimestamp = new Date(expiresAt).getTime();
  if (Number.isNaN(expiresAtTimestamp)) return false;

  return expiresAtTimestamp > Date.now();
}

const handleRedirect = async ({
  req,
}: {
  req: NextRequest;
}): Promise<{
  res: NextResponse;
  redirect: boolean;
}> => {
  let hasSession = false;
  try {
    const sessionData = await auth.api.getSession({ headers: req.headers });
    hasSession = hasActiveSession(sessionData);
  } catch {
    hasSession = false;
  }

  const isAuthPath = isPathMatched(req.nextUrl.pathname, AUTH_PATHS);
  const isPublicPath = isPathMatched(req.nextUrl.pathname, PUBLIC_PATHS);
  const isProtectedPath = !isPublicPath && !isAuthPath;

  // If current path is not public and user is not logged in, redirect to login page
  if (isProtectedPath && !hasSession) {
    const loginUrl = new URL('/login', req.nextUrl.origin);
    loginUrl.searchParams.set(
      'nextUrl',
      req.nextUrl.pathname + req.nextUrl.search
    );

    return { res: NextResponse.redirect(loginUrl), redirect: true };
  }

  // If current path ends with /login and user is logged in, redirect to dashboard page
  if (isAuthPath && hasSession) {
    const nextUrl = req.nextUrl.searchParams.get('nextUrl');
    const sanitizedNextUrl = sanitizeUrl(nextUrl) || '/dashboard';
    const redirectUrl = new URL(sanitizedNextUrl, req.nextUrl.origin);

    return { res: NextResponse.redirect(redirectUrl), redirect: true };
  }

  const nextRes = NextResponse.next();

  return { res: nextRes, redirect: false };
};

export async function proxy(req: NextRequest) {
  if (req.nextUrl.pathname.startsWith('/api')) {
    return NextResponse.next();
  }

  // Handle special cases for public, authenticating paths
  const { res: nextRes, redirect } = await handleRedirect({ req });
  if (redirect) return nextRes;

  return intlMiddleware(req);
}

export const config = {
  matcher: [
    /*
     * Match all request paths except for the ones starting with:
     * - _next/static (static files)
     * - _next/image (image optimization files)
     * - favicon.ico (favicon file)
     * - robots.txt (SEO)
     * - sitemap.xml (SEO)
     * - site.webmanifest (legacy PWA manifest)
     * - manifest.webmanifest (PWA manifest generated by Next.js)
     * - sw.js (service worker)
     * - monitoring (analytics)
     * - .well-known (domain verification files)
     * Excludes files with the following extensions for static assets:
     * - svg
     * - png
     * - jpg
     * - jpeg
     * - mp3
     * - wav
     * - ogg
     * - m4a
     * - pdf
     * - gif
     * - webp
     */

    '/((?!_next/static|_next/image|favicon.ico|robots.txt|sitemap.xml|site.webmanifest|manifest.webmanifest|sw.js|serwist|monitoring|\\.well-known|.*\\.(?:svg|png|jpg|jpeg|mp3|wav|ogg|m4a|pdf|gif|webp)$).*)',
  ],
};
